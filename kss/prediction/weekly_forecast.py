"""周度预测 —— 每周 Top 选股推荐."""

from __future__ import annotations

from datetime import datetime

import pandas as pd

from kss.models.base import ModelBase
from kss.models.registry import ModelRegistry
from kss.strategies.base import StrategyBase


class WeeklyForecast:
    """周度预测器.

    基于策略生成每周优选股票列表，并提供 Markdown 格式化周报。
    """

    def __init__(
        self,
        model_registry: ModelRegistry,
        strategy: StrategyBase,
    ) -> None:
        """初始化周度预测器.

        Args:
            model_registry: 模型注册中心。
            strategy: 选股策略实例。
        """
        self.model_registry = model_registry
        self.strategy = strategy

    # ------------------------------------------------------------------ #
    # 核心预测
    # ------------------------------------------------------------------ #

    def generate(
        self,
        factor_df: pd.DataFrame,
        feature_cols: list[str],
        model: ModelBase,
    ) -> pd.DataFrame:
        """生成本周 Top 选股推荐.

        使用策略的 ``generate_signals`` 获取当前最新日期的买入信号，
        并补充预测收益与排名信息。

        Args:
            factor_df: 包含因子与行情数据的 DataFrame。
            feature_cols: 模型输入特征列名列表。
            model: 已训练好的模型实例。

        Returns:
            周度选股 DataFrame，列为::

                - ``symbol``      : 股票代码
                - ``pred_score``  : 模型原始打分
                - ``daily_rank``  : 当日排名分位数
                - ``pred_return`` : 预测周度收益率（基于打分映射）
                - ``confidence``  : 置信度
                - ``signal``      : 固定为 "buy"
        """
        latest_date = factor_df["trade_date"].max()
        signals = self.strategy.generate_signals(
            factor_df, feature_cols, model, date=latest_date
        )

        if signals.empty:
            return signals

        # 避免对调用方传入的 DataFrame 产生副作用
        signals = signals.copy()

        # 补充预测收益与置信度
        score = signals["pred_score"]
        z = (score - score.mean()) / (score.std() + 1e-8)
        # 周度收益粗略估计：比日度更宽
        signals["pred_return"] = (z * 0.02).clip(-0.10, 0.10)
        signals["confidence"] = signals["daily_rank"].apply(
            lambda r: abs(r - 0.5) * 2 if pd.notna(r) else 0.0
        )

        return signals.sort_values("pred_score", ascending=False).reset_index(drop=True)

    # ------------------------------------------------------------------ #
    # 格式化输出
    # ------------------------------------------------------------------ #

    def format_weekly(self, picks_df: pd.DataFrame) -> str:
        """将周度选股 DataFrame 格式化为 Markdown 文本.

        Args:
            picks_df: :meth:`generate` 返回的周度选股 DataFrame。

        Returns:
            Markdown 格式的周度选股报告字符串。
        """
        lines: list[str] = []
        today = datetime.now().strftime("%Y-%m-%d")
        lines.append(f"# KSS 周度选股报告 ({today})")
        lines.append("")
        lines.append(f"> 本期共选出 **{len(picks_df)}** 只优选股票")
        lines.append("")

        if picks_df.empty:
            lines.append("*本周无符合条件的选股信号。*")
            lines.append("")
            lines.append("---")
            lines.append("*Generated by KSS WeeklyForecast*")
            return "\n".join(lines)

        lines.append("## 本周 Top 推荐")
        lines.append("")
        lines.append("| 排名 | 代码 | 打分 | 预测收益 | 排名分位 | 置信度 |")
        lines.append("|------|------|------|----------|----------|--------|")

        for rank, (_, row) in enumerate(picks_df.iterrows(), start=1):
            pred_ret = row.get("pred_return", 0.0)
            daily_rank = row.get("daily_rank", 0.0)
            conf = row.get("confidence", 0.0)
            lines.append(
                f"| {rank} | {row['symbol']} | "
                f"{row['pred_score']:.4f} | "
                f"{pred_ret*100:+.2f}% | "
                f"{daily_rank:.1%} | "
                f"{conf:.1%} |"
            )

        lines.append("")

        # 板块/风格摘要（若 symbol 可推断）
        lines.append("## 配置建议")
        lines.append("- 建议等权或按置信度加权构建组合")
        lines.append("- 单票仓位不超过 10%，控制集中度风险")
        lines.append("- 下周初根据开盘情况微调入场节奏")
        lines.append("")

        lines.append("---")
        lines.append("*Generated by KSS WeeklyForecast*")
        return "\n".join(lines)
